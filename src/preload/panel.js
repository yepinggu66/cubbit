function on(channel, cb) {
  const handler = (_e, payload) => cb(payload);
  ipcRenderer.on(channel, handler);
  return () => ipcRenderer.removeListener(channel, handler);
}

contextBridge.exposeInMainWorld('cubbit', {
  // 静态目录数据（皮肤 palette 等），非 IPC 通道
  catalog: require('../shared/catalog.js'),
  panel: {
    init: () => ipcRenderer.invoke(INVOKE.APP_STATE),
    state: () => ipcRenderer.invoke(INVOKE.APP_STATE),
    invoke: (channel, payload) => {
      if (!ALLOWED.has(channel)) {
        return Promise.reject(new Error(`IPC channel not allowed: ${channel}`));
      }
      return ipcRenderer.invoke(channel, payload);
    },
    onState: (cb) => on(EVENTS.STATE_CHANGED, cb),
    room: {
      get: () => ipcRenderer.invoke(INVOKE.COUPLE_SCENE_GET),
      set: (payload) => ipcRenderer.invoke(INVOKE.COUPLE_SCENE_SET, payload),
      capture: () => ipcRenderer.invoke(INVOKE.COUPLE_SCENE_CAPTURE),
      onScene: (cb) => on(EVENTS.COUPLE_SCENE, cb),
    },
    onNav: (cb) => on(EVENTS.PANEL_NAV, cb),
    onAiMessage: (cb) => on(EVENTS.AI_MESSAGE, cb),
    onCoupleRt: (cb) => on(EVENTS.COUPLE_RT, cb),
    window: (action) => ipcRenderer.invoke(INVOKE.APP_PANEL_WINDOW, { action }),
    skinPreview: (id, seconds) => ipcRenderer.invoke(INVOKE.SKIN_PREVIEW, { id, seconds }),
    openPanel: (name) => ipcRenderer.invoke(INVOKE.APP_PANEL_OPEN, { name }),
    openExternal: (url) => ipcRenderer.invoke(INVOKE.APP_OPEN_EXTERNAL, { url }),
    quit: () => ipcRenderer.invoke(INVOKE.APP_QUIT),
    close: () => ipcRenderer.invoke(INVOKE.APP_PANEL_WINDOW, { action: 'close' }),
  },
});
